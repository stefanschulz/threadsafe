<?php

declare(strict_types=1);

namespace ThreadSafe\Database;

use PDO;
use PDOException;
use PDOStatement;
use Throwable;

/**
 * Thin wrapper around PDO for MariaDB (the only supported server): prepared statements, exceptions on errors,
 * identifier quoting, transactions.
 */
final class Connection
{
    private function __construct(
        private readonly PDO $pdo,
        public readonly DatabaseSettings $settings,
        public readonly string $serverVersion,
    ) {
    }

    /**
     * @throws ConnectionFailed if the server cannot be reached
     */
    public static function open(DatabaseSettings $settings): self
    {
        try {
            $pdo = new PDO(
                sprintf('mysql:host=%s;port=%d;dbname=%s;charset=utf8mb4', $settings->host, $settings->port, $settings->name),
                $settings->user,
                $settings->password,
                [
                    PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION,
                    PDO::ATTR_DEFAULT_FETCH_MODE => PDO::FETCH_ASSOC,
                    PDO::ATTR_EMULATE_PREPARES => false,
                ],
            );
        } catch (PDOException $e) {
            throw new ConnectionFailed(
                sprintf('Cannot connect to database "%s" on %s:%d as "%s": %s', $settings->name, $settings->host, $settings->port, $settings->user, $e->getMessage()),
                0,
                $e,
            );
        }

        $version = $pdo->query('SELECT VERSION()');
        $serverVersion = $version === false ? '' : (string) $version->fetchColumn();

        return new self($pdo, $settings, $serverVersion);
    }

    public function isMariaDb(): bool
    {
        return stripos($this->serverVersion, 'mariadb') !== false;
    }

    /** Table name with the shop prefix. */
    public function table(string $name): string
    {
        return $this->settings->prefix . $name;
    }

    public function quote(string $identifier): string
    {
        return '`' . str_replace('`', '``', $identifier) . '`';
    }

    /**
     * @param list<scalar|null> $parameters
     *
     * @return list<array<string, mixed>>
     */
    public function select(string $sql, array $parameters = []): array
    {
        return array_values($this->run($sql, $parameters)->fetchAll());
    }

    /**
     * First column of the first row, or null if there is none.
     *
     * @param list<scalar|null> $parameters
     */
    public function scalar(string $sql, array $parameters = []): mixed
    {
        $value = $this->run($sql, $parameters)->fetchColumn();

        return $value === false ? null : $value;
    }

    /**
     * Runs a data-changing statement and returns the number of affected rows.
     *
     * @param list<scalar|null> $parameters
     */
    public function execute(string $sql, array $parameters = []): int
    {
        return $this->run($sql, $parameters)->rowCount();
    }

    /** Auto-increment value generated by the last INSERT. */
    public function lastInsertId(): int
    {
        return (int) $this->pdo->lastInsertId();
    }

    public function tableExists(string $table): bool
    {
        return (int) $this->scalar(
            'SELECT COUNT(*) FROM information_schema.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = ?',
            [$table],
        ) > 0;
    }

    /**
     * Runs $work in a transaction; rolls back and rethrows if it throws.
     *
     * @template T
     *
     * @param callable(): T $work
     *
     * @return T
     */
    public function transaction(callable $work): mixed
    {
        $this->pdo->beginTransaction();
        try {
            $result = $work();
            $this->pdo->commit();

            return $result;
        } catch (Throwable $e) {
            if ($this->pdo->inTransaction()) {
                $this->pdo->rollBack();
            }

            throw $e;
        }
    }

    /**
     * @param list<scalar|null> $parameters
     */
    private function run(string $sql, array $parameters): PDOStatement
    {
        $statement = $this->pdo->prepare($sql);
        $statement->execute($parameters);

        return $statement;
    }
}

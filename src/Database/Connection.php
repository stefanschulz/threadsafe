<?php

declare(strict_types=1);

namespace ThreadSafe\Database;

use Throwable;

/**
 * The database connection of ThreadSafe for MariaDB and MySQL: prepared statements, exceptions on errors, identifier
 * quoting, transactions. The PHP interface that does the talking ({@see PdoDriver} or {@see MysqliDriver}) is chosen
 * by {@see DatabaseSettings::$driver}; the rest of the program does not know which it is.
 */
final class Connection
{
    private function __construct(
        private readonly Driver $driver,
        public readonly DatabaseSettings $settings,
        public readonly ServerInfo $server,
    ) {
    }

    /**
     * @throws ConnectionFailed if the server cannot be reached or the chosen PHP interface is not available
     */
    public static function open(DatabaseSettings $settings): self
    {
        $driver = match ($settings->driver) {
            DatabaseSettings::PDO => PdoDriver::connect($settings),
            DatabaseSettings::MYSQLI => MysqliDriver::connect($settings),
            default => self::automatic($settings),
        };

        try {
            $version = (string) $driver->scalar('SELECT VERSION()', []);
        } catch (DatabaseError $e) {
            throw new ConnectionFailed(PdoDriver::describe($settings, $e->getMessage()), 0, $e);
        }

        return new self($driver, $settings, ServerInfo::parse($version));
    }

    /** `pdo_mysql` if it is loaded, otherwise `mysqli`. */
    private static function automatic(DatabaseSettings $settings): Driver
    {
        if (extension_loaded('pdo_mysql')) {
            return PdoDriver::connect($settings);
        }
        if (extension_loaded('mysqli')) {
            return MysqliDriver::connect($settings);
        }

        throw new ConnectionFailed('Neither the PHP extension pdo_mysql nor mysqli is loaded.');
    }

    /** "pdo" or "mysqli": the PHP interface in use. */
    public function driverName(): string
    {
        return $this->driver->name();
    }

    /** The version string the server reported. */
    public function serverVersion(): string
    {
        return $this->server->raw;
    }

    /** Table name with the shop prefix. */
    public function table(string $name): string
    {
        return $this->settings->prefix . $name;
    }

    public function quote(string $identifier): string
    {
        return '`' . str_replace('`', '``', $identifier) . '`';
    }

    /** The name of a table without the shop prefix. */
    public function unprefixed(string $table): string
    {
        $prefix = $this->settings->prefix;

        return $prefix !== '' && str_starts_with($table, $prefix) ? substr($table, strlen($prefix)) : $table;
    }

    /** A value as a quoted SQL string literal, for the few places that build a condition as text. */
    public function quotedString(string $value): string
    {
        return $this->driver->quoteString($value);
    }

    /**
     * @param list<scalar|null> $parameters
     *
     * @return list<array<string, mixed>>
     */
    public function select(string $sql, array $parameters = []): array
    {
        return $this->driver->select($sql, $parameters);
    }

    /**
     * First column of the first row, or null if there is none.
     *
     * @param list<scalar|null> $parameters
     */
    public function scalar(string $sql, array $parameters = []): mixed
    {
        return $this->driver->scalar($sql, $parameters);
    }

    /**
     * Runs a data-changing statement and returns the number of affected rows.
     *
     * @param list<scalar|null> $parameters
     */
    public function execute(string $sql, array $parameters = []): int
    {
        return $this->driver->execute($sql, $parameters);
    }

    /**
     * Rows of a SELECT one by one, with constant memory; no other statement may run on this connection until the
     * generator is used up or dropped.
     *
     * @param list<scalar|null> $parameters
     *
     * @return \Generator<int, array<string, mixed>>
     */
    public function stream(string $sql, array $parameters = []): \Generator
    {
        return $this->driver->stream($sql, $parameters);
    }

    /** Starts a transaction with a consistent snapshot of all InnoDB tables; end it with {@see endSnapshot()}. */
    public function startSnapshot(): void
    {
        $this->driver->beginSnapshot();
    }

    public function endSnapshot(): void
    {
        $this->driver->endSnapshot();
    }

    /** Auto-increment value generated by the last INSERT. */
    public function lastInsertId(): int
    {
        return $this->driver->lastInsertId();
    }

    public function tableExists(string $table): bool
    {
        return (int) $this->scalar(
            'SELECT COUNT(*) FROM information_schema.TABLES WHERE TABLE_SCHEMA = DATABASE() AND TABLE_NAME = ?',
            [$table],
        ) > 0;
    }

    /**
     * Runs $work in a transaction; rolls back and rethrows if it throws.
     *
     * @template T
     *
     * @param callable(): T $work
     *
     * @return T
     */
    public function transaction(callable $work): mixed
    {
        $this->driver->begin();
        try {
            $result = $work();
            $this->driver->commit();

            return $result;
        } catch (Throwable $e) {
            if ($this->driver->inTransaction()) {
                $this->driver->rollBack();
            }

            throw $e;
        }
    }
}

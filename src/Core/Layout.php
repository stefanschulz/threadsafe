<?php

declare(strict_types=1);

namespace ThreadSafe\Core;

use RuntimeException;

/**
 * The small files that an installation from a release has outside its releases and that never change with a release
 * (docs/PHASE7.md 3.2): the stub `index.php` of the document root, the command `<home>/bin/threadsafe`, and the `.htaccess` files.
 * The installer writes them; the update does not touch them.
 *
 * The stub and the command are written for old PHP versions (no namespaces, closures, short arrays, `__DIR__` or types, no name with
 * a backslash), because on a host whose PHP is too old their only job is to say so. The home is written into them as a string.
 */
final class Layout
{
    /** The stub of the document root: finds the active release, then hands over to the interface of that release. */
    public static function stub(string $home): string
    {
        return str_replace('{HOME}', self::quote($home), <<<'STUB'
<?php
// ThreadSafe - generated by the installer, do not edit. This file never changes with a release: a new version is a new directory below
// the home and a new pointer (docs/PHASE7.md 3.2). It is written for old PHP versions, so that the message below can be shown.
if (version_compare(PHP_VERSION, '8.4.0', '<')) {
    header('HTTP/1.1 500 Internal Server Error');
    header('Content-Type: text/plain; charset=utf-8');
    echo 'ThreadSafe needs PHP 8.4 or newer (this is ' . PHP_VERSION . "). Ask your host to switch the PHP version of this site.\n";
    exit;
}
$home = {HOME};
$pointer = @file_get_contents($home . '/current.php');
$lines = explode("\n", (string) $pointer, 2);
$data = isset($lines[1]) ? json_decode($lines[1], true) : null;
$release = is_array($data) && isset($data['release']) && is_string($data['release']) ? $data['release'] : '';
if (!preg_match('/^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?$/', $release) || !is_file($home . '/releases/' . $release . '/vendor/autoload.php')) {
    header('HTTP/1.1 503 Service Unavailable');
    header('Content-Type: text/plain; charset=utf-8');
    echo "ThreadSafe is not installed correctly: the pointer to the active release is missing or damaged. Install it again, or restore current.php from a backup of the home directory.\n";
    exit;
}
define('THREADSAFE_PROGRAM_DIR', $home . '/releases/' . $release);
putenv('THREADSAFE_DATA=' . $home . '/data');
require THREADSAFE_PROGRAM_DIR . '/vendor/autoload.php';
call_user_func('ThreadSafe\\Admin\\Entry::run');

STUB);
    }

    /** `<home>/bin/threadsafe`: the command line that always runs the active release, so that a cron job survives an update. */
    public static function command(string $home): string
    {
        return str_replace('{HOME}', self::quote($home), <<<'COMMAND'
#!/usr/bin/env php
<?php
// ThreadSafe - generated by the installer, do not edit. It runs the command of the active release (docs/PHASE7.md 3.2).
if (version_compare(PHP_VERSION, '8.4.0', '<')) {
    fwrite(defined('STDERR') ? STDERR : fopen('php://stderr', 'wb'), 'ThreadSafe needs PHP 8.4 or newer (this is ' . PHP_VERSION . ").\n");
    exit(1);
}
$home = {HOME};
$pointer = @file_get_contents($home . '/current.php');
$lines = explode("\n", (string) $pointer, 2);
$data = isset($lines[1]) ? json_decode($lines[1], true) : null;
$release = is_array($data) && isset($data['release']) && is_string($data['release']) ? $data['release'] : '';
if (!preg_match('/^[0-9]+\.[0-9]+\.[0-9]+(-[0-9A-Za-z.-]+)?$/', $release) || !is_file($home . '/releases/' . $release . '/bin/threadsafe')) {
    fwrite(defined('STDERR') ? STDERR : fopen('php://stderr', 'wb'), "ThreadSafe is not installed correctly: the pointer to the active release is missing or damaged.\n");
    exit(1);
}
define('THREADSAFE_SCRIPT', __FILE__);
putenv('THREADSAFE_DATA=' . $home . '/data');
require $home . '/releases/' . $release . '/bin/threadsafe';

COMMAND);
    }

    /** The `.htaccess` of the document root: every address that is not a file goes to the stub. */
    public static function documentRootHtaccess(): string
    {
        return <<<'HTACCESS'
# ThreadSafe: every address that is not a file is answered by index.php (the pages are /login, /profiles/shop ...). Without
# mod_rewrite set "web.prettyUrls" to false in data/config.json; the pages are then index.php?route=/login.
Options -Indexes

<IfModule mod_rewrite.c>
    RewriteEngine On
    RewriteCond %{REQUEST_FILENAME} !-f
    RewriteCond %{REQUEST_FILENAME} !-d
    RewriteRule ^ index.php [L]
</IfModule>

HTACCESS;
    }

    /** The `.htaccess` that closes a directory below the document root (the weaker layout, docs/PHASE7.md 3.2). */
    public static function closedHtaccess(): string
    {
        return <<<'HTACCESS'
# ThreadSafe: nothing in this directory is meant to be fetched over the web.
Options -Indexes
<IfModule mod_authz_core.c>
    Require all denied
</IfModule>
<IfModule !mod_authz_core.c>
    Order deny,allow
    Deny from all
</IfModule>

HTACCESS;
    }

    private static function quote(string $home): string
    {
        $home = rtrim(str_replace('\\', '/', $home), '/');
        if ($home === '' || str_contains($home, "\0") || str_contains($home, "\n")) {
            throw new RuntimeException('The home directory is not usable.');
        }

        return var_export($home, true);
    }

    private function __construct()
    {
    }
}

<?php

declare(strict_types=1);

namespace ThreadSafe\Build;

/**
 * The first part of `restore.php`: the only part that every PHP version has to be able to read. It is written in the syntax of PHP
 * 5.2 - no namespaces, closures, short arrays, `__DIR__`, `?:` or types, and no name with a backslash in it - because a parse
 * error in an old PHP would show nothing but a white page. It
 *
 * 1. refuses to go on below PHP 8.4, with a message that says what to do;
 * 2. on the web, shows an explanation and writes nothing as long as the key file is missing (docs/PHASE3.md 3.2);
 * 3. unpacks the payload behind `__halt_compiler()` once - the bundled code and the plugin files the code reads from disk - into
 *    `.threadsafe-restore/` (mode 0700, closed to the web), keyed by size and time of the file so that a new upload unpacks anew;
 * 4. loads the bundle and hands over to {@see \ThreadSafe\Web\Entry}.
 *
 * Payload (after the stub, deflated): for each file `<name> TAB <size> LF <bytes>`; the file `bundle.php` is the code, every other
 * one is written below `.threadsafe-restore/program/`, which is what THREADSAFE_PROGRAM_DIR names.
 */
final class RestoreStub
{
    public static function source(string $version): string
    {
        return str_replace('{VERSION}', $version, <<<'STUB'
<?php
// ThreadSafe restore tool {VERSION} - generated by tools/build-restore.php, do not edit.
// This first part is written for old PHP versions (it must parse everywhere, 5.2 and up); the program itself follows the line
// "__halt_compiler" and needs PHP 8.4.
if (version_compare(PHP_VERSION, '8.4.0', '<')) {
    if (PHP_SAPI !== 'cli' && !headers_sent()) {
        header('HTTP/1.1 500 Internal Server Error');
        header('Content-Type: text/plain; charset=utf-8');
    }
    echo "This restore tool needs PHP 8.4 or newer; this server runs PHP " . PHP_VERSION . ".\n";
    echo "Ask your host for a newer PHP version (often a setting in the control panel) and load this page again.\n";
    exit(1);
}
if (!function_exists('gzinflate')) {
    echo "The PHP extension zlib is missing; this restore tool cannot unpack itself without it. Ask your host to enable it.\n";
    exit(1);
}
$threadsafeBase = dirname(__FILE__);
if (isset($_SERVER['REQUEST_METHOD']) && !is_file($threadsafeBase . '/restore-key.php')) {
    // on the web nothing happens, and nothing is written, until the person has put a key file next to this one
    if (!headers_sent()) {
        header('HTTP/1.1 403 Forbidden');
        header('Content-Type: text/plain; charset=utf-8');
        header('Cache-Control: no-store');
    }
    echo "This restore tool does nothing until you give it a key.\n\n";
    echo "Create a file named restore-key.php next to " . basename(__FILE__) . " with this content (choose your own secret of at least 8 characters):\n\n";
    echo "<?php return 'a secret you choose';\n\n";
    echo "It is a PHP file on purpose: a plain text file would be served to anyone who asks for it. Then load this page again.\n";
    exit(1);
}
$threadsafeDir = $threadsafeBase . '/.threadsafe-restore';
$threadsafeBundle = $threadsafeDir . '/bundle-' . filesize(__FILE__) . '-' . filemtime(__FILE__) . '.php';
if (!is_file($threadsafeBundle)) {
    if (!is_dir($threadsafeDir) && !@mkdir($threadsafeDir, 0700)) {
        echo "Cannot create the directory " . $threadsafeDir . ". Make " . $threadsafeBase . " writable for PHP.\n";
        exit(1);
    }
    @chmod($threadsafeDir, 0700);
    if (!is_file($threadsafeDir . '/.htaccess')) {
        @file_put_contents($threadsafeDir . '/.htaccess', "# Nothing in here is for the web.\n<IfModule mod_authz_core.c>\n    Require all denied\n</IfModule>\n<IfModule !mod_authz_core.c>\n    Order deny,allow\n    Deny from all\n</IfModule>\n");
    }
    if (!is_file($threadsafeDir . '/index.html')) {
        @file_put_contents($threadsafeDir . '/index.html', '');
    }
    $threadsafeIn = fopen(__FILE__, 'rb');
    fseek($threadsafeIn, __COMPILER_HALT_OFFSET__);
    $threadsafeData = gzinflate(stream_get_contents($threadsafeIn));
    fclose($threadsafeIn);
    if ($threadsafeData === false) {
        echo "This file is damaged (the program in it cannot be unpacked). Upload it again.\n";
        exit(1);
    }
    $threadsafeCode = '';
    $threadsafeAt = 0;
    $threadsafeLength = strlen($threadsafeData);
    while ($threadsafeAt < $threadsafeLength) {
        $threadsafeEnd = strpos($threadsafeData, "\n", $threadsafeAt);
        $threadsafeHead = explode("\t", substr($threadsafeData, $threadsafeAt, $threadsafeEnd - $threadsafeAt));
        $threadsafeSize = (int) $threadsafeHead[1];
        $threadsafeContent = substr($threadsafeData, $threadsafeEnd + 1, $threadsafeSize);
        $threadsafeAt = $threadsafeEnd + 1 + $threadsafeSize;
        if ($threadsafeHead[0] === 'bundle.php') {
            $threadsafeCode = $threadsafeContent;
            continue;
        }
        $threadsafeTarget = $threadsafeDir . '/program/' . $threadsafeHead[0];
        if (!is_dir(dirname($threadsafeTarget))) {
            mkdir(dirname($threadsafeTarget), 0700, true);
        }
        file_put_contents($threadsafeTarget, $threadsafeContent);
    }
    unset($threadsafeData, $threadsafeContent);
    foreach (glob($threadsafeDir . '/bundle-*.php') as $threadsafeOld) {
        @unlink($threadsafeOld);
    }
    file_put_contents($threadsafeBundle . '.tmp', $threadsafeCode);
    rename($threadsafeBundle . '.tmp', $threadsafeBundle);
    unset($threadsafeCode);
}
define('THREADSAFE_PROGRAM_DIR', $threadsafeDir . '/program');
require $threadsafeBundle;
exit((int) call_user_func('ThreadSafe\Web\Entry::run', __FILE__));
__halt_compiler();
STUB);
    }

    private function __construct()
    {
    }
}

<?php

declare(strict_types=1);

namespace ThreadSafe\Build;

/**
 * The first part of every single-file tool that is handed out - `threadsafe-restore.php`, `threadsafe-install.php`, `threadsafe-backup.php` -: the only
 * part that every PHP version has to be able to read. It is written in the syntax of PHP 5.2 (no namespaces, closures, short arrays, `__DIR__`, `?:` or
 * types, no name with a backslash) because a parse error on an old PHP would show nothing but a white page. It
 *
 * 1. refuses to go on below PHP 8.4, with a message that says what to do;
 * 2. on the web, explains and writes nothing as long as the key file is missing (docs/PHASE3.md 3.2);
 * 3. unpacks the program behind `__halt_compiler()` once into a hidden directory next to the file (mode 0700, closed to the web), keyed by size and time
 *    of the file so that a new upload unpacks anew;
 * 4. loads the bundle and hands over to the entry class of the tool.
 *
 * The tools differ in four places only, which are the parameters below: their names and files, the way the payload is laid out after the stub (a list
 * of files, or the length of the code and a ZIP archive behind it), the entry class, and a few words of the header. Until phase 12 the restore tool and
 * the installer had a stub each, the same code twice (docs/PHASE12.md 3.8).
 */
final class ToolStub
{
    /** The payload is `<name> TAB <size> LF <bytes>` for each file, deflated as one; `bundle.php` is the code, every other file goes below `program/`. */
    private const string FILES = 'files';

    /** The payload is the length of the deflated code and a line feed, the code, and then a ZIP archive ({@see ZipShift}). */
    private const string LENGTH = 'length';

    public static function restore(string $version): string
    {
        return self::source($version, [
            'label' => 'restore tool', 'notice' => 'restore', 'key' => 'threadsafe-restore-key.php', 'directory' => '.threadsafe-restore',
            'generator' => 'tools/build-restore.php', 'itself' => 'the program', 'afterHalt' => '', 'payload' => self::FILES,
            'entry' => 'ThreadSafe\Web\Entry::run', 'damaged' => 'The program in it cannot be unpacked.', 'damagedHint' => '',
        ]);
    }

    public static function installer(string $version): string
    {
        return self::source($version, [
            'label' => 'installer', 'notice' => 'installer', 'key' => 'threadsafe-install-key.php', 'directory' => '.threadsafe-install',
            'generator' => 'tools/build-release.php', 'itself' => 'the installer',
            'afterHalt' => ' Behind it is the release package, a ZIP archive: "unzip threadsafe-install.php" opens it too.', 'payload' => self::LENGTH,
            'entry' => 'ThreadSafe\Install\Entry::run', 'damaged' => 'The installer in it cannot be unpacked.',
            'damagedHint' => ', and compare its SHA-256 with the one on the release page',
        ]);
    }

    public static function backup(string $version): string
    {
        return self::source($version, [
            'label' => 'backup tool', 'notice' => 'backup', 'key' => 'threadsafe-backup-key.php', 'directory' => '.threadsafe-backup',
            'generator' => 'tools/build-backup.php', 'itself' => 'the program', 'afterHalt' => '', 'payload' => self::FILES,
            'entry' => 'ThreadSafe\Web\BackupEntry::run', 'damaged' => 'The program in it cannot be unpacked.', 'damagedHint' => '',
        ]);
    }

    /**
     * @param array{label: string, notice: string, key: string, directory: string, generator: string, itself: string, afterHalt: string, payload: string, entry: string, damaged: string, damagedHint: string} $tool
     */
    private static function source(string $version, array $tool): string
    {
        $template = strtr(<<<'STUB'
<?php
// ThreadSafe {LABEL} {VERSION} - generated by {GENERATOR}, do not edit.
// This first part is written for old PHP versions (it must parse everywhere, 5.2 and up); {ITSELF} itself follows the line
// "__halt_compiler" and needs PHP 8.4.{AFTERHALT}
// Whatever stops this file is shown as a page (the block at the end of the loop below), not as a line of text.
$threadsafeNotice = array();
$threadsafeBase = dirname(__FILE__);
do {
if (version_compare(PHP_VERSION, '8.4.0', '<')) {
    $threadsafeNotice = array('500 Internal Server Error', 'PHP is too old', "<p>This {LABEL} needs PHP 8.4 or newer; this server runs PHP " . htmlspecialchars(PHP_VERSION) . ".</p><p>Ask your host for a newer PHP version (often a setting in the control panel) and load this page again.</p>");
    break;
}
if (!function_exists('gzinflate')) {
    $threadsafeNotice = array('500 Internal Server Error', 'The PHP extension zlib is missing', "<p>This {LABEL} cannot unpack itself without the PHP extension <code>zlib</code>.</p><p>Ask your host to enable it and load this page again.</p>");
    break;
}
if (isset($_SERVER['REQUEST_METHOD']) && !is_file($threadsafeBase . '/{KEY}')) {
    // on the web nothing happens, and nothing is written, until the person has put a key file next to this one
    $threadsafeNotice = array('403 Forbidden', 'No access key yet', "<p>This {LABEL} does nothing until you give it a key.</p><p>Create a file named <code>{KEY}</code> next to <code>" . htmlspecialchars(basename(__FILE__)) . "</code> with this content (choose your own secret of at least 8 characters):</p><pre><code>&lt;?php return 'a secret you choose';</code></pre><p class='help'>It is a PHP file on purpose: a plain text file would be served to anyone who asks for it. Then reload this page.</p>");
    break;
}
$threadsafeDir = $threadsafeBase . '/{DIRECTORY}';
$threadsafeBundle = $threadsafeDir . '/bundle-' . filesize(__FILE__) . '-' . filemtime(__FILE__) . '.php';
if (!is_file($threadsafeBundle)) {
    if (!is_dir($threadsafeDir) && !@mkdir($threadsafeDir, 0700)) {
        $threadsafeNotice = array('500 Internal Server Error', 'A directory cannot be made', "<p>This {LABEL} cannot create the directory <code>" . htmlspecialchars($threadsafeDir) . "</code>.</p><p>Make <code>" . htmlspecialchars($threadsafeBase) . "</code> writable for PHP and load this page again.</p>");
        break;
    }
    @chmod($threadsafeDir, 0700);
    if (!is_file($threadsafeDir . '/.htaccess')) {
        @file_put_contents($threadsafeDir . '/.htaccess', "# Nothing in here is for the web.\n<IfModule mod_authz_core.c>\n    Require all denied\n</IfModule>\n<IfModule !mod_authz_core.c>\n    Order deny,allow\n    Deny from all\n</IfModule>\n");
    }
    if (!is_file($threadsafeDir . '/index.html')) {
        @file_put_contents($threadsafeDir . '/index.html', '');
    }
{UNPACK}
}
{HANDOVER}
} while (false);
{NOTICE}
__halt_compiler();
STUB, [
            '{UNPACK}' => $tool['payload'] === self::FILES ? self::UNPACK_FILES : self::UNPACK_LENGTH,
            '{HANDOVER}' => $tool['payload'] === self::FILES ? self::HANDOVER_FILES : self::HANDOVER_LENGTH,
            '{NOTICE}' => StubNotice::source($tool['notice']),
        ]);

        // a second pass: the pieces that were put in carry placeholders of their own
        return strtr($template, [
            '{LABEL}' => $tool['label'], '{KEY}' => $tool['key'], '{DIRECTORY}' => $tool['directory'], '{GENERATOR}' => $tool['generator'],
            '{ITSELF}' => $tool['itself'], '{AFTERHALT}' => $tool['afterHalt'], '{ENTRY}' => $tool['entry'], '{VERSION}' => $version,
            '{DAMAGED}' => $tool['damaged'], '{DAMAGEDHINT}' => $tool['damagedHint'],
        ]);
    }

    private const string UNPACK_FILES = <<<'PHP'
    $threadsafeIn = fopen(__FILE__, 'rb');
    fseek($threadsafeIn, __COMPILER_HALT_OFFSET__);
    $threadsafeData = gzinflate(stream_get_contents($threadsafeIn));
    fclose($threadsafeIn);
    if ($threadsafeData === false) {
        $threadsafeNotice = array('500 Internal Server Error', 'This file is damaged', "<p>{DAMAGED}</p><p>Upload <code>" . htmlspecialchars(basename(__FILE__)) . "</code> again{DAMAGEDHINT}.</p>");
        break;
    }
    $threadsafeCode = '';
    $threadsafeAt = 0;
    $threadsafeLength = strlen($threadsafeData);
    while ($threadsafeAt < $threadsafeLength) {
        $threadsafeEnd = strpos($threadsafeData, "\n", $threadsafeAt);
        $threadsafeHead = explode("\t", substr($threadsafeData, $threadsafeAt, $threadsafeEnd - $threadsafeAt));
        $threadsafeSize = (int) $threadsafeHead[1];
        $threadsafeContent = substr($threadsafeData, $threadsafeEnd + 1, $threadsafeSize);
        $threadsafeAt = $threadsafeEnd + 1 + $threadsafeSize;
        if ($threadsafeHead[0] === 'bundle.php') {
            $threadsafeCode = $threadsafeContent;
            continue;
        }
        $threadsafeTarget = $threadsafeDir . '/program/' . $threadsafeHead[0];
        if (!is_dir(dirname($threadsafeTarget))) {
            mkdir(dirname($threadsafeTarget), 0700, true);
        }
        file_put_contents($threadsafeTarget, $threadsafeContent);
    }
    unset($threadsafeData, $threadsafeContent);
    foreach (glob($threadsafeDir . '/bundle-*.php') as $threadsafeOld) {
        @unlink($threadsafeOld);
    }
    file_put_contents($threadsafeBundle . '.tmp', $threadsafeCode);
    rename($threadsafeBundle . '.tmp', $threadsafeBundle);
    unset($threadsafeCode);
PHP;

    private const string UNPACK_LENGTH = <<<'PHP'
    $threadsafeIn = fopen(__FILE__, 'rb');
    fseek($threadsafeIn, __COMPILER_HALT_OFFSET__);
    $threadsafeLength = (int) trim(fgets($threadsafeIn, 32));
    $threadsafeCode = $threadsafeLength > 0 ? gzinflate(fread($threadsafeIn, $threadsafeLength)) : false;
    fclose($threadsafeIn);
    if ($threadsafeCode === false) {
        $threadsafeNotice = array('500 Internal Server Error', 'This file is damaged', "<p>{DAMAGED}</p><p>Upload <code>" . htmlspecialchars(basename(__FILE__)) . "</code> again{DAMAGEDHINT}.</p>");
        break;
    }
    foreach (glob($threadsafeDir . '/bundle-*.php') as $threadsafeOld) {
        @unlink($threadsafeOld);
    }
    file_put_contents($threadsafeBundle . '.tmp', $threadsafeCode);
    rename($threadsafeBundle . '.tmp', $threadsafeBundle);
    unset($threadsafeCode);
PHP;

    private const string HANDOVER_FILES = <<<'PHP'
define('THREADSAFE_PROGRAM_DIR', $threadsafeDir . '/program');
require $threadsafeBundle;
exit((int) call_user_func('{ENTRY}', __FILE__));
PHP;

    private const string HANDOVER_LENGTH = <<<'PHP'
require $threadsafeBundle;
exit((int) call_user_func('{ENTRY}', __FILE__));
PHP;

    private function __construct()
    {
    }
}

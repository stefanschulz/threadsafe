<?php

declare(strict_types=1);

namespace ThreadSafe\Build;

/**
 * The first part of `install.php`: the only part that every PHP version has to be able to read (docs/PHASE7.md 3.3). Like the stub of
 * `restore.php` it is written in the syntax of PHP 5.2 (no namespaces, closures, short arrays, `__DIR__`, `?:` or types, no name with a
 * backslash), because a parse error on an old PHP would show nothing but a white page. It
 *
 * 1. refuses to go on below PHP 8.4, with a message that says what to do;
 * 2. on the web, explains and writes nothing as long as the key file `install-key.php` is missing;
 * 3. unpacks the installer's code, which follows the line `__halt_compiler`, once into `.threadsafe-install/` (mode 0700, closed to the
 *    web), keyed by size and time of the file;
 * 4. loads that code and hands over to {@see \ThreadSafe\Install\Entry}.
 *
 * Behind the line `__halt_compiler();` come the length of the deflated code and a line feed, the deflated code, and then the release
 * package, a ZIP archive whose offsets are shifted by everything before it ({@see ZipShift}).
 */
final class InstallStub
{
    public static function source(string $version): string
    {
        return strtr(<<<'STUB'
<?php
// ThreadSafe installer {VERSION} - generated by tools/build-release.php, do not edit.
// This first part is written for old PHP versions (it must parse everywhere, 5.2 and up); the installer itself follows the line
// "__halt_compiler" and needs PHP 8.4. Behind it is the release package, a ZIP archive: "unzip install.php" opens it too.
// Whatever stops this file is shown as a page (the block at the end of the loop below), not as a line of text.
$threadsafeNotice = array();
$threadsafeBase = dirname(__FILE__);
do {
if (version_compare(PHP_VERSION, '8.4.0', '<')) {
    $threadsafeNotice = array('500 Internal Server Error', 'PHP is too old', "<p>This installer needs PHP 8.4 or newer; this server runs PHP " . htmlspecialchars(PHP_VERSION) . ".</p><p>Ask your host for a newer PHP version (often a setting in the control panel) and load this page again.</p>");
    break;
}
if (!function_exists('gzinflate')) {
    $threadsafeNotice = array('500 Internal Server Error', 'The PHP extension zlib is missing', "<p>This installer cannot unpack itself without the PHP extension <code>zlib</code>.</p><p>Ask your host to enable it and load this page again.</p>");
    break;
}
if (isset($_SERVER['REQUEST_METHOD']) && !is_file($threadsafeBase . '/install-key.php')) {
    // on the web nothing happens, and nothing is written, until the person has put a key file next to this one
    $threadsafeNotice = array('403 Forbidden', 'No access key yet', "<p>This installer does nothing until you give it a key.</p><p>Create a file named <code>install-key.php</code> next to <code>" . htmlspecialchars(basename(__FILE__)) . "</code> with this content (choose your own secret of at least 8 characters):</p><pre><code>&lt;?php return 'a secret you choose';</code></pre><p class='help'>It is a PHP file on purpose: a plain text file would be served to anyone who asks for it. Then reload this page.</p>");
    break;
}
$threadsafeDir = $threadsafeBase . '/.threadsafe-install';
$threadsafeBundle = $threadsafeDir . '/bundle-' . filesize(__FILE__) . '-' . filemtime(__FILE__) . '.php';
if (!is_file($threadsafeBundle)) {
    if (!is_dir($threadsafeDir) && !@mkdir($threadsafeDir, 0700)) {
        $threadsafeNotice = array('500 Internal Server Error', 'A directory cannot be made', "<p>This installer cannot create the directory <code>" . htmlspecialchars($threadsafeDir) . "</code>.</p><p>Make <code>" . htmlspecialchars($threadsafeBase) . "</code> writable for PHP and load this page again.</p>");
        break;
    }
    @chmod($threadsafeDir, 0700);
    if (!is_file($threadsafeDir . '/.htaccess')) {
        @file_put_contents($threadsafeDir . '/.htaccess', "# Nothing in here is for the web.\n<IfModule mod_authz_core.c>\n    Require all denied\n</IfModule>\n<IfModule !mod_authz_core.c>\n    Order deny,allow\n    Deny from all\n</IfModule>\n");
    }
    if (!is_file($threadsafeDir . '/index.html')) {
        @file_put_contents($threadsafeDir . '/index.html', '');
    }
    $threadsafeIn = fopen(__FILE__, 'rb');
    fseek($threadsafeIn, __COMPILER_HALT_OFFSET__);
    $threadsafeLength = (int) trim(fgets($threadsafeIn, 32));
    $threadsafeCode = $threadsafeLength > 0 ? gzinflate(fread($threadsafeIn, $threadsafeLength)) : false;
    fclose($threadsafeIn);
    if ($threadsafeCode === false) {
        $threadsafeNotice = array('500 Internal Server Error', 'This file is damaged', "<p>The installer in it cannot be unpacked.</p><p>Upload <code>" . htmlspecialchars(basename(__FILE__)) . "</code> again, and compare its SHA-256 with the one on the release page.</p>");
        break;
    }
    foreach (glob($threadsafeDir . '/bundle-*.php') as $threadsafeOld) {
        @unlink($threadsafeOld);
    }
    file_put_contents($threadsafeBundle . '.tmp', $threadsafeCode);
    rename($threadsafeBundle . '.tmp', $threadsafeBundle);
    unset($threadsafeCode);
}
require $threadsafeBundle;
exit((int) call_user_func('ThreadSafe\Install\Entry::run', __FILE__));
} while (false);
{NOTICE}
__halt_compiler();
STUB, ['{NOTICE}' => StubNotice::source('installer'), '{VERSION}' => $version]);
    }

    private function __construct()
    {
    }
}

<?php

declare(strict_types=1);

namespace ThreadSafe\Tests\Unit\Build;

use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\TestCase;
use ThreadSafe\Build\ToolStub;

/**
 * The stub that the restore tool, the installer and the backup tool share (docs/PHASE12.md 3.8): old PHP can read it, the key file is asked for before
 * anything is written, every tool has its own names, and the three differ in those names and in the way the payload is laid out, in nothing else.
 */
final class ToolStubTest extends TestCase
{
    /** @return iterable<string, array{string, string, string, string}> stub, key file, entry class, directory */
    public static function tools(): iterable
    {
        yield 'restore tool' => [ToolStub::restore('test'), 'threadsafe-restore-key.php', 'ThreadSafe\\Web\\Entry::run', '.threadsafe-restore'];
        yield 'installer' => [ToolStub::installer('test'), 'threadsafe-install-key.php', 'ThreadSafe\\Install\\Entry::run', '.threadsafe-install'];
        yield 'backup tool' => [ToolStub::backup('test'), 'threadsafe-backup-key.php', 'ThreadSafe\\Web\\BackupEntry::run', '.threadsafe-backup'];
    }

    #[DataProvider('tools')]
    public function testTheStubUsesOnlyWhatPhp52CanRead(string $stub, string $key, string $entry, string $directory): void
    {
        $tokens = token_get_all(substr($stub, 0, (int) strpos($stub, '__halt_compiler') + strlen('__halt_compiler')));
        $forbidden = [
            T_NAMESPACE => 'namespace', T_NS_SEPARATOR => 'a name with a backslash', T_NAME_QUALIFIED => 'a qualified name', T_NAME_FULLY_QUALIFIED => 'a qualified name',
            T_FN => 'fn', T_DIR => '__DIR__', T_COALESCE => '??', T_POW => '**', T_USE => 'use', T_CLASS => 'class', T_TRAIT => 'trait',
            T_YIELD => 'yield', T_FINALLY => 'finally', T_GOTO => 'goto', T_INSTEADOF => 'insteadof', T_SPACESHIP => '<=>', T_ELLIPSIS => '...', T_PUBLIC => 'visibility', T_STATIC => 'static',
            T_FUNCTION => 'a function or closure',
        ];
        $previous = null;
        foreach ($tokens as $token) {
            if (is_array($token) && isset($forbidden[$token[0]])) {
                self::fail('The stub uses ' . $forbidden[$token[0]] . ' (line ' . $token[2] . '), which old PHP cannot parse.');
            }
            if ($token === '[' && ($previous === '=' || $previous === '(' || $previous === ',' || (is_array($previous) && in_array($previous[0], [T_RETURN, T_DOUBLE_ARROW], true)))) {
                self::fail('The stub uses a short array.');
            }
            if ($token === '?') {
                self::fail('The stub uses ?: or a nullable type.');
            }
            if (!is_array($token) || $token[0] !== T_WHITESPACE) {
                $previous = $token;
            }
        }
        self::assertStringContainsString("'$entry'", $stub, 'the entry is called by name from a string');
    }

    #[DataProvider('tools')]
    public function testTheKeyFileIsAskedForBeforeAnythingIsWrittenOnTheWeb(string $stub, string $key, string $entry, string $directory): void
    {
        self::assertLessThan(strpos($stub, 'mkdir'), strpos($stub, "$key'"), 'the key check comes before the first directory is made');
        self::assertStringContainsString("is_file(\$threadsafeBase . '/$key')", $stub);
    }

    #[DataProvider('tools')]
    public function testEveryToolHasItsOwnDirectoryAndNoWordOfTheOthers(string $stub, string $key, string $entry, string $directory): void
    {
        self::assertStringContainsString("\$threadsafeBase . '/$directory'", $stub);
        foreach (['restore', 'install', 'backup'] as $other) {
            if (!str_contains($key, "-$other-")) {
                self::assertStringNotContainsString("threadsafe-$other-key.php", $stub);
                self::assertStringNotContainsString(".threadsafe-$other'", $stub);
            }
        }
        self::assertSame(0, preg_match('/\{(LABEL|KEY|DIRECTORY|GENERATOR|ITSELF|AFTERHALT|ENTRY|VERSION|DAMAGED|DAMAGEDHINT|UNPACK|HANDOVER|NOTICE)\}/', $stub), 'no placeholder is left over');
    }

    public function testTheVersionIsInTheHeader(): void
    {
        self::assertStringContainsString('// ThreadSafe restore tool 1.2.3 - generated by tools/build-restore.php', ToolStub::restore('1.2.3'));
        self::assertStringContainsString('// ThreadSafe installer 1.2.3 - generated by tools/build-release.php', ToolStub::installer('1.2.3'));
        self::assertStringContainsString('// ThreadSafe backup tool 1.2.3 - generated by tools/build-backup.php', ToolStub::backup('1.2.3'));
    }

    public function testTheBackupStubIsTheRestoreStubWithOtherNames(): void
    {
        $asRestore = strtr(ToolStub::backup('test'), [
            'backup tool' => 'restore tool', 'threadsafe-backup-key.php' => 'threadsafe-restore-key.php', '.threadsafe-backup' => '.threadsafe-restore',
            'tools/build-backup.php' => 'tools/build-restore.php', 'ThreadSafe\\Web\\BackupEntry::run' => 'ThreadSafe\\Web\\Entry::run', 'ThreadSafe backup' => 'ThreadSafe restore',
            "ThreadSafe backup tool" => "ThreadSafe restore tool",
        ]);

        self::assertSame(ToolStub::restore('test'), $asRestore, 'the two differ in names only: the payload of both is the list of files');
    }

    public function testTheInstallerKeepsItsOwnLayoutOfThePayload(): void
    {
        $installer = ToolStub::installer('test');

        self::assertStringContainsString('fgets($threadsafeIn, 32)', $installer, 'the length of the code, then the code, then a ZIP archive');
        self::assertStringNotContainsString('THREADSAFE_PROGRAM_DIR', $installer);
        self::assertStringContainsString("define('THREADSAFE_PROGRAM_DIR'", ToolStub::restore('test'));
        self::assertStringContainsString('compare its SHA-256 with the one on the release page', $installer);
    }
}
